"""Code generation for the GPU AprilTag detector in photon-targeting.

Subcommands:
  shaders <shader_dir> <out.cpp>
      Compile every compute shader listed in <shader_dir>/SHADERS.txt to SPIR-V with
      glslangValidator and embed them as C++ arrays (the vkapriltag EmbeddedShaders.h API).
  symbols <repo_root>
      Generate photon/gpu/symbol_prefix.h, which renames every global symbol of the vendored
      AprilTag 3 copy and every Vulkan entry point vkapriltag calls to a photon_gpu_ prefix, and
      vulkan_loader_shim.cpp, which defines those Vulkan entry points by loading libvulkan.so.1
      at runtime. This keeps the vendored AprilTag from clashing with WPILib's copy in the same
      process, and lets the library load on machines without Vulkan.
"""

import hashlib
import pathlib
import re
import subprocess
import sys
import tempfile

PREFIX = "photon_gpu_"
HEADER = """// Copyright (C) Photon Vision.
// Generated by scripts/gpu_apriltag_codegen.py. Do not edit.
"""


def gen_shaders(shader_dir: pathlib.Path, out: pathlib.Path) -> None:
    names = [
        n.strip() for n in (shader_dir / "SHADERS.txt").read_text().split() if n.strip()
    ]
    entries = []
    with tempfile.TemporaryDirectory() as tmp:
        for name in sorted(names):
            src = shader_dir / name
            spv = pathlib.Path(tmp) / (name + ".spv")
            subprocess.run(
                [
                    "glslangValidator",
                    "--target-env",
                    "vulkan1.1",
                    f"-I{shader_dir}",
                    "-o",
                    str(spv),
                    str(src),
                ],
                check=True,
                stdout=subprocess.DEVNULL,
            )
            data = spv.read_bytes()
            assert len(data) % 4 == 0, f"{name}: SPIR-V size not a multiple of 4"
            base = re.sub(r"\.comp$", "", name)
            entries.append((base, data))

    digest_input = "".join(f"{n}:{hashlib.md5(d).hexdigest()};" for n, d in entries)
    corpus = hashlib.md5(digest_input.encode()).hexdigest()[:16]

    lines = [HEADER, f"// Shaders embedded: {len(entries)}\n"]
    lines.append('#include "vkapriltag/vk/EmbeddedShaders.h"\n\n#include <cstring>\n')
    lines.append("namespace apriltag_vulkan::vk {\nnamespace {\n")
    for name, data in entries:
        words = [
            int.from_bytes(data[i : i + 4], "little") for i in range(0, len(data), 4)
        ]
        sym = re.sub(r"[^A-Za-z0-9_]", "_", name)
        lines.append(f"const uint32_t k_{sym}[] = {{")
        for i in range(0, len(words), 8):
            lines.append(
                "    " + ", ".join(f"0x{w:08x}" for w in words[i : i + 8]) + ","
            )
        lines.append("};\n")
    lines.append("const EmbeddedShader kShaders[] = {")
    for name, data in entries:
        sym = re.sub(r"[^A-Za-z0-9_]", "_", name)
        lines.append(f'    {{"{name}", k_{sym}, {len(data)}u}},')
    lines.append("};\n")
    lines.append(f"constexpr size_t kShaderCount = {len(entries)};\n")
    lines.append("}  // namespace\n")
    lines.append(
        """const EmbeddedShader *FindEmbeddedShader(const char *name) {
  if (name == nullptr) return nullptr;
  for (size_t i = 0; i < kShaderCount; ++i) {
    if (std::strcmp(kShaders[i].name, name) == 0) return &kShaders[i];
  }
  return nullptr;
}

bool HasEmbeddedShaders() { return kShaderCount > 0; }
"""
    )
    lines.append(f"uint64_t EmbeddedShaderCorpusHash() {{ return 0x{corpus}ull; }}\n")
    lines.append("}  // namespace apriltag_vulkan::vk")
    out.write_text("\n".join(lines) + "\n")
    print(f"Embedded {len(entries)} shaders into {out}")


def apriltag_symbols(root: pathlib.Path) -> list:
    """Global symbols defined by the vendored AprilTag sources."""
    at = root / "photon-targeting/src/main/native/thirdparty/apriltag3"
    syms = set()
    with tempfile.TemporaryDirectory() as tmp:
        for src in sorted((at / "src").rglob("*.c")):
            obj = pathlib.Path(tmp) / (src.stem + ".o")
            subprocess.run(
                [
                    "gcc",
                    "-std=gnu17",
                    "-O0",
                    "-w",
                    "-c",
                    f"-I{at / 'include'}",
                    f"-I{at / 'include' / 'common'}",
                    "-o",
                    str(obj),
                    str(src),
                ],
                check=True,
            )
            out = subprocess.run(
                ["nm", "--defined-only", "-g", str(obj)],
                check=True,
                capture_output=True,
                text=True,
            ).stdout
            for line in out.splitlines():
                parts = line.split()
                if len(parts) == 3:
                    syms.add(parts[2])
    return sorted(syms)


PROTO_RE = re.compile(
    r"VKAPI_ATTR\s+(?P<ret>[\w\s\*]+?)\s+VKAPI_CALL\s+(?P<name>vk\w+)\s*\((?P<params>[^;]*?)\);",
    re.DOTALL,
)


def vulkan_prototypes(root: pathlib.Path) -> dict:
    core = (
        root
        / "photon-targeting/src/main/native/thirdparty/vulkan-headers/include/vulkan/vulkan_core.h"
    ).read_text()
    protos = {}
    for m in PROTO_RE.finditer(core):
        params = " ".join(m.group("params").split())
        protos[m.group("name")] = (" ".join(m.group("ret").split()), params)
    return protos


def used_vulkan_functions(root: pathlib.Path, protos: dict) -> list:
    vk = root / "photon-targeting/src/main/native/thirdparty/vkapriltag"
    used = set()
    for f in list((vk / "src").rglob("*.cpp")) + list((vk / "include").rglob("*.h")):
        for m in re.finditer(r"\b(vk[A-Z]\w*)\s*\(", f.read_text()):
            if m.group(1) in protos:
                used.add(m.group(1))
    return sorted(used)


def split_params(params: str) -> list:
    if params.strip() in ("", "void"):
        return []
    out, depth, cur = [], 0, ""
    for ch in params:
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
            continue
        depth += ch in "[("
        depth -= ch in "])"
        cur += ch
    out.append(cur.strip())
    return out


def param_name(p: str) -> str:
    p = re.sub(r"\[.*\]$", "", p).strip()
    return re.findall(r"\w+", p)[-1]


def gen_symbols(root: pathlib.Path) -> None:
    gpu = root / "photon-targeting/src/main/native/gpu"
    at_syms = apriltag_symbols(root)
    protos = vulkan_prototypes(root)
    vk_funcs = used_vulkan_functions(root, protos)

    header = [HEADER]
    header.append(
        """// Force-included into every translation unit of the GPU AprilTag library. Renames the
// vendored AprilTag 3 symbols so they cannot collide with WPILib's apriltag library loaded in
// the same JVM, and the Vulkan entry points so they resolve to vulkan_loader_shim.cpp instead of a
// link-time libvulkan dependency.
#pragma once
"""
    )
    for s in at_syms:
        header.append(f"#define {s} {PREFIX}{s}")
    header.append("")
    for f in vk_funcs:
        header.append(f"#define {f} {PREFIX}{f}")
    (gpu / "include/photon/gpu/symbol_prefix.h").write_text("\n".join(header) + "\n")

    shim = [HEADER]
    shim.append(
        """// Defines every Vulkan entry point the GPU AprilTag detector uses by looking it up in
// libvulkan.so.1 at runtime, so the JNI library loads (and reports "Vulkan unavailable") on
// machines without a Vulkan loader instead of failing to load at all.

#include <dlfcn.h>

#include <mutex>

#include <vulkan/vulkan.h>

#include "photon/gpu/VulkanLoader.h"

namespace photon::gpu {
namespace {
std::once_flag g_once;
void *g_lib = nullptr;

void *Lib() {
  std::call_once(g_once, [] {
    g_lib = dlopen("libvulkan.so.1", RTLD_NOW | RTLD_LOCAL);
    if (g_lib == nullptr) g_lib = dlopen("libvulkan.so", RTLD_NOW | RTLD_LOCAL);
  });
  return g_lib;
}

template <typename T>
T Load(const char *name) {
  void *lib = Lib();
  return lib == nullptr ? nullptr : reinterpret_cast<T>(dlsym(lib, name));
}
}  // namespace

bool VulkanLoaderAvailable() { return Lib() != nullptr; }
}  // namespace photon::gpu

extern "C" {
"""
    )
    for f in vk_funcs:
        ret, params = protos[f]
        plist = split_params(params)
        args = ", ".join(param_name(p) for p in plist)
        shim.append(
            f"VKAPI_ATTR {ret} VKAPI_CALL {f}({params if plist else 'void'}) {{"
        )
        shim.append(f'  static const auto fn = photon::gpu::Load<PFN_{f}>("{f}");')
        if ret == "void":
            shim.append(f"  if (fn != nullptr) fn({args});")
        elif ret == "VkResult":
            shim.append(
                f"  return fn != nullptr ? fn({args}) : VK_ERROR_INITIALIZATION_FAILED;"
            )
        else:
            shim.append(f"  return fn != nullptr ? fn({args}) : {ret}{{}};")
        shim.append("}\n")
    shim.append('}  // extern "C"')
    (gpu / "cpp/vulkan_loader_shim.cpp").write_text("\n".join(shim) + "\n")
    print(
        f"Prefixed {len(at_syms)} AprilTag symbols and {len(vk_funcs)} Vulkan functions"
    )


def main() -> None:
    if len(sys.argv) >= 2 and sys.argv[1] == "shaders" and len(sys.argv) == 4:
        gen_shaders(pathlib.Path(sys.argv[2]), pathlib.Path(sys.argv[3]))
    elif len(sys.argv) == 3 and sys.argv[1] == "symbols":
        gen_symbols(pathlib.Path(sys.argv[2]))
    else:
        print(__doc__)
        sys.exit(1)


if __name__ == "__main__":
    main()
